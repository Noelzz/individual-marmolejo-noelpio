public class ForLoopStatement {
    static void main(String[] args) {
        // [Syntax] For Loop

        /*
            for (intitialization; condition; inc/dec) {
                statement / body of the loop
            }
         */

        for (int i = 0; i<=10; i++) {
            System.out.print(i + " ");
        }
    }
}
